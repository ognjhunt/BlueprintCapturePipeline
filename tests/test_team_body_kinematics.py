    for prim in stage.Traverse():
        recorded = prim.GetMetadata("displayName") if prim.HasAuthoredMetadata("displayName") else None
        names.setdefault(prim.GetName(), recorded or prim.GetName())
    return usd, manifest, {**config, "usd_source_names": names}


