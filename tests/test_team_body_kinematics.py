def _quatf(rotation):
    from pxr import Gf

    matrix = Gf.Matrix3d(*[float(v) for v in np.asarray(rotation).reshape(-1)])
    return Gf.Quatf(matrix.GetTranspose().ExtractRotation().GetQuat())


def _rpy_quatf(rpy):
    """urdf-usd-converter utils.float3_to_quatf."""
    from pxr import Gf

    roll, pitch, yaw = rpy
    rotation = (Gf.Rotation(Gf.Vec3d(1, 0, 0), math.degrees(roll)) * Gf.Rotation(Gf.Vec3d(0, 1, 0), math.degrees(pitch))
                * Gf.Rotation(Gf.Vec3d(0, 0, 1), math.degrees(yaw)))
    return Gf.Quatf(rotation.GetQuat())


def _numbers(node, key, default):
    text = node.get(key) if node is not None else None
    return [float(v) for v in text.split()] if text else list(default)


def _place(prim, origin):
    from pxr import Gf, UsdGeom

    xform = UsdGeom.Xformable(prim)
    xform.AddTranslateOp().Set(Gf.Vec3d(*_numbers(origin, "xyz", (0, 0, 0))))
    xform.AddOrientOp().Set(_rpy_quatf(_numbers(origin, "rpy", (0, 0, 0))))


def _sibling_name(parent, name):
    """usdex NameCache.getPrimName: unique among siblings."""
    safe, index = _usdex_prim_name(name), 0
    candidate = safe
    while parent.GetChild(candidate):
        index += 1
        candidate = f"{safe}_{index}"
    return candidate


def kinematic_usd(urdf: Path, output: Path) -> Path:
    """The URDF as urdf-usd-converter 0.1.3 (link.py, link_hierarchy.py, geometry.py) authors it, flattened."""
    from pxr import Gf, Usd, UsdGeom, UsdPhysics

    root = SafeXML.fromstring(urdf.read_bytes())
    links = {link.get("name"): link for link in root.findall("link")}
    joints = root.findall("joint")
    incoming = {joint.find("child").get("link"): joint for joint in joints}
    children = {}
    for joint in joints:
        children.setdefault(joint.find("parent").get("link"), []).append(joint)
    root_link = next(name for name in links if name not in incoming)

    def ghost(name):
        inertial, link = links[name].find("inertial"), links[name]
        mass = inertial.find("mass") if inertial is not None else None
        value = float(mass.get("value")) if mass is not None and mass.get("value") is not None else None
        if inertial is None or value is None:
            zero = True
        elif value > 0:
            zero = False
        else:
            inertia = inertial.find("inertia")
            zero = inertia is None or all(float(inertia.get(k, 0) or 0) == 0 for k in ("ixx", "iyy", "izz"))
        return zero and link.find("visual") is None and link.find("collision") is None

    def fixed_ghost(name):
        return ghost(name) and (name == root_link or incoming[name].get("type") == "fixed")

    stage = Usd.Stage.CreateInMemory()
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    default = stage.DefinePrim("/" + _usdex_prim_name(root.get("name")), "Xform")
    stage.SetDefaultPrim(default)
    paths, articulated = {}, [False]

    def convert(parent, name):
        prim = stage.DefinePrim(parent.GetPath().AppendChild(_sibling_name(parent, name)), "Xform")
        if prim.GetName() != name:
            prim.SetDisplayName(name)
        paths[name] = prim.GetPath()
        if not fixed_ghost(name):
            UsdPhysics.RigidBodyAPI.Apply(prim)
            if not (name == root_link and ghost(name)) and not articulated[0]:
                UsdPhysics.ArticulationRootAPI.Apply(prim)
                articulated[0] = True
        for kind in ("visual", "collision"):
            for node in links[name].findall(kind):
                shape = node.find("geometry")[0]
                if shape.tag == "mesh":
                    label = Path(shape.get("filename")).stem
                    if Path(shape.get("filename")).suffix.lower() not in {".stl", ".obj", ".dae"}:
                        continue  # mesh.py: unsupported mesh format (e.g. GLB visuals)
                else:
                    label = shape.tag
                path = prim.GetPath().AppendChild(_sibling_name(prim, node.get("name") or label))
                if shape.tag == "box":
                    geometry = UsdGeom.Cube.Define(stage, path)
                    geometry.CreateSizeAttr(1.0)
                elif shape.tag == "cylinder":
                    geometry = UsdGeom.Cylinder.Define(stage, path)
                    geometry.CreateRadiusAttr(float(shape.get("radius")))
                    geometry.CreateHeightAttr(float(shape.get("length")))
                    geometry.CreateAxisAttr("Z")
                elif shape.tag == "sphere":
                    geometry = UsdGeom.Sphere.Define(stage, path)
                    geometry.CreateRadiusAttr(float(shape.get("radius")))
                else:  # the source mesh bytes are not retained: a 2 cm placeholder
                    geometry = UsdGeom.Mesh.Define(stage, path)
                    geometry.CreatePointsAttr([(x, y, z) for x in (-.01, .01) for y in (-.01, .01) for z in (-.01, .01)])
                _place(geometry.GetPrim(), node.find("origin"))
                if shape.tag == "box":
                    geometry.AddScaleOp().Set(Gf.Vec3f(*_numbers(shape, "size", (1, 1, 1))))
                if kind == "collision":
                    UsdPhysics.CollisionAPI.Apply(geometry.GetPrim())
        for joint in children.get(name, []):
            child = convert(prim, joint.find("child").get("link"))
            _place(child, joint.find("origin"))
        return prim

    geometry_scope = stage.DefinePrim(default.GetPath().AppendChild("Geometry"), "Scope")
    convert(geometry_scope, root_link)
    scope = stage.DefinePrim(default.GetPath().AppendChild("Physics"), "Scope")
    cache = UsdGeom.XformCache()

    def world(path):
        return np.asarray(cache.GetLocalToWorldTransform(stage.GetPrimAtPath(path)), dtype=float).T

    authored = [] if ghost(root_link) else [("root_joint", "fixed", None, root_link, None)]
    authored += [(j.get("name"), j.get("type"), j.find("parent").get("link"), j.find("child").get("link"), j)
                 for j in joints]
    defined = {}
    for name, kind, parent, child, node in authored:
        if not stage.GetPrimAtPath(paths[child]).HasAPI(UsdPhysics.RigidBodyAPI):
            continue
        body0 = default.GetPath() if parent is None or (parent == root_link and ghost(root_link)) else paths[parent]
        types = {"fixed": UsdPhysics.FixedJoint, "revolute": UsdPhysics.RevoluteJoint,
                 "continuous": UsdPhysics.RevoluteJoint, "prismatic": UsdPhysics.PrismaticJoint}
        joint = types[kind].Define(stage, scope.GetPath().AppendChild(_sibling_name(scope, name)))
        if joint.GetPrim().GetName() != name:
            joint.GetPrim().SetDisplayName(name)
        joint.CreateBody0Rel().SetTargets([body0])
        joint.CreateBody1Rel().SetTargets([paths[child]])
        # usdex JointFrame(Body1, origin, identity): body1's origin, expressed on both bodies.
        frame0 = np.linalg.inv(world(body0)) @ world(paths[child])
        align = np.eye(3)
        if kind != "fixed":
            axis = np.asarray(_numbers(node.find("axis"), "xyz", (1, 0, 0)))
            axis /= np.linalg.norm(axis)
            token = next((t for t, e in zip("XYZ", np.eye(3)) if np.allclose(axis, e)), None)
            if token is None:  # usdex aligns the joint's X axis with an arbitrary axis
                token = "X"
                align = np.asarray(Gf.Matrix3d().SetRotate(Gf.Rotation(Gf.Vec3d(1, 0, 0), Gf.Vec3d(*axis)))).T
            joint.CreateAxisAttr(token)
        joint.CreateLocalPos0Attr(Gf.Vec3f(*frame0[:3, 3]))
        joint.CreateLocalRot0Attr(_quatf(frame0[:3, :3] @ align))
        joint.CreateLocalPos1Attr(Gf.Vec3f(0, 0, 0))
        joint.CreateLocalRot1Attr(_quatf(align))
        limit = node.find("limit") if node is not None else None
        if kind == "revolute":
            joint.CreateLowerLimitAttr(math.degrees(float(limit.get("lower", 0))))
            joint.CreateUpperLimitAttr(math.degrees(float(limit.get("upper", 0))))
        elif kind == "prismatic":
            joint.CreateLowerLimitAttr(float(limit.get("lower", 0)))
            joint.CreateUpperLimitAttr(float(limit.get("upper", 0)))
        defined[name] = joint.GetPrim()
    for name, kind, parent, child, node in authored:
        mimic = node.find("mimic") if node is not None else None
        if name in defined and mimic is not None and mimic.get("joint") in defined:
            from pxr import Sdf

            prim = defined[name]
            prim.AddAppliedSchema("NewtonMimicAPI")
            prim.CreateAttribute("newton:mimicEnabled", Sdf.ValueTypeNames.Bool).Set(True)
            prim.CreateAttribute("newton:mimicCoef1", Sdf.ValueTypeNames.Float).Set(float(mimic.get("multiplier", 1)))
            prim.CreateRelationship("newton:mimicJoint").AddTarget(defined[mimic.get("joint")].GetPath())
    _isaac_apply_fix_base(stage)
    output.parent.mkdir(parents=True, exist_ok=True)
    stage.GetRootLayer().Export(str(output))
    return output


