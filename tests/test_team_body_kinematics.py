@pytest.mark.parametrize("identity", BODIES)
def test_chain_from_the_prepared_model_reproduces_the_source_urdf(models, identity):
    usd, manifest, config = models(identity)
    urdf = FIXTURES / identity / "robot.urdf"
    found = kinematics.body_arm_chains(usd, manifest)
    assert found["unassessed"] == {}
    assert [chain.name for chain in found["chains"].values()] == [arm["name"] for arm in manifest["arms"]]
    generator = np.random.default_rng(7)
    worst_position = worst_angle = 0.0
    for arm in manifest["arms"]:
        chain = found["chains"][arm["name"]]
        assert chain.joint_names == tuple(arm["joint_names"])
        assert np.allclose(chain.authored, 0.0, atol=1e-6)
        assert not [note for note in chain.notes if note.startswith("joint_frames_inconsistent")]
        source = {name: _source(name, config) for name in chain.joint_names}
        base, tool = _source(arm["base_link"], config), _source(arm["tool_link"], config)
        for q in _random_joints(chain, generator, 40):
            reference = _urdf_frames(urdf, {source[n]: v for n, v in zip(chain.joint_names, q)})
            pose = kinematics.forward(chain, q)
            base_from = np.linalg.inv(reference[base])
            expected = {"tool": base_from @ reference[tool], "tcp": base_from @ reference[tool] @ chain.tool_from_tcp}
            expected.update({body.source_name: base_from @ reference[body.source_name] for body in chain.bodies})
            actual = {"tool": pose.tool, "tcp": pose.tcp, **{b.source_name: f for b, f in zip(chain.bodies, pose.bodies)}}
            for name, frame in expected.items():
                worst_position = max(worst_position, float(np.linalg.norm(actual[name][:3, 3] - frame[:3, 3])))
                worst_angle = max(worst_angle, _angle(actual[name], frame))
        # The base sits in the robot root where the source puts it.
        reference = _urdf_frames(urdf, {})
        root = _parse_urdf(urdf)["base_frame"]
        assert np.allclose(chain.root_from_base, np.linalg.inv(reference[root]) @ reference[base], atol=1e-6)
    # Isaac authors positions and orientations in single precision.
    assert worst_position < 2e-6 and worst_angle < 2e-6, (worst_position, worst_angle)


def test_franka_chain_matches_the_published_franka_model(models):
    """FR3 and the DROID Franka (FER/Panda) share one chain; the generic one must reproduce ``_frames``."""
    usd, manifest, _ = models("franka_research_3_robotiq_2f85_sim")
    chain = kinematics.body_arm_chains(usd, manifest)["chains"]["arm"]
    assert [b.source_name for b in chain.bodies] == [f"fr3_link{i}" for i in range(8)] + ["robotiq_85_base_link"]
    limits = np.asarray(FRANKA_JOINT_LIMITS_RAD)
    generator = np.random.default_rng(2026)
    worst_position = worst_angle = 0.0
    for q in limits[:, 0] + (limits[:, 1] - limits[:, 0]) * generator.random((2000, 7)):
        dh = _frames(q)
        pose = kinematics.forward(chain, q)
        # link 0 is the base; links 1-7 are the moving links; the flange (frame 8) is the tool mount.
        pairs = [(pose.bodies[i], dh[i]) for i in range(8)] + [(pose.tool, dh[8])]
        for actual, expected in pairs:
            worst_position = max(worst_position, float(np.linalg.norm(actual[:3, 3] - expected[:3, 3])))
            worst_angle = max(worst_angle, _angle(actual, expected))
    print(f"franka_dh_cross_check max_position_m={worst_position:.3g} max_rotation_rad={worst_angle:.3g}")
    assert worst_position < 1e-6 and worst_angle < 1e-6


