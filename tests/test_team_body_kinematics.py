@pytest.mark.parametrize("identity", BODIES)
def test_ik_round_trip_holds_limits_and_refuses_the_unreachable(models, identity):
    usd, manifest, _ = models(identity)
    chains = kinematics.body_arm_chains(usd, manifest)["chains"]
    generator = np.random.default_rng(11)
    for chain in chains.values():
        for q in _random_joints(chain, generator, 12):
            target = kinematics.forward(chain, q).tcp
            result = kinematics.solve(chain, target, position_tolerance_m=1e-4, orientation_tolerance_rad=1e-3)
            assert result.ok, (chain.name, result.as_dict())
            assert np.all(result.joints >= chain.lower - 1e-12) and np.all(result.joints <= chain.upper + 1e-12)
            reached = kinematics.forward(chain, result.joints).tcp
            assert np.linalg.norm(reached[:3, 3] - target[:3, 3]) < 1e-4 and _angle(reached, target) < 1e-3
        # Far beyond what the chain can span: refused without a search.
        far = kinematics.forward(chain, chain.reset).tcp.copy()
        far[:3, 3] = far[:3, 3] / max(np.linalg.norm(far[:3, 3]), 1e-9) * (chain.reach_bound_m + 1.0) * 1.5
        missed = kinematics.solve(chain, far)
        assert (missed.ok, missed.failure, missed.detail) == (False, "ik_unreachable", "beyond_reach_bound")
        # Seeds outside the limits are clipped, never returned outside them.
        wild = kinematics.solve(chain, kinematics.forward(chain, chain.reset).tcp, seeds=[chain.upper + 5.0])
        assert wild.ok and np.all(wild.joints <= chain.upper + 1e-12)


@pytest.mark.parametrize("identity", BIMANUAL)
def test_bimanual_arms_are_solved_independently(models, identity):
    usd, manifest, config = models(identity)
    chains = list(kinematics.body_arm_chains(usd, manifest)["chains"].values())
    assert len(chains) == 2
    left, right = chains
    assert not set(left.joint_names) & set(right.joint_names)
    assert not {b.path for b in left.bodies} & {b.path for b in right.bodies}
    assert not np.allclose(left.root_from_base[:3, 3], right.root_from_base[:3, 3])
    urdf = FIXTURES / identity / "robot.urdf"
    root = _parse_urdf(urdf)["base_frame"]
    generator = np.random.default_rng(5)
    for _ in range(6):
        values = {chain.name: _random_joints(chain, generator, 1)[0] for chain in chains}
        everything = {_source(n, config): v for chain in chains for n, v in zip(chain.joint_names, values[chain.name])}
        reference = _urdf_frames(urdf, everything)
        targets = {}
        for chain in chains:
            arm = next(a for a in manifest["arms"] if a["name"] == chain.name)
            expected = (np.linalg.inv(reference[root]) @ reference[_source(arm["tool_link"], config)]
                        @ chain.tool_from_tcp)
            # Each arm's TCP in the robot root depends on its own joints only.
            assert np.allclose(chain.root_from_base @ kinematics.forward(chain, values[chain.name]).tcp, expected,
                               atol=2e-6)
            targets[chain.name] = np.linalg.inv(chain.root_from_base) @ expected
        solved = {chain.name: kinematics.solve(chain, targets[chain.name], position_tolerance_m=1e-4,
                                               orientation_tolerance_rad=1e-3) for chain in chains}
        assert all(result.ok for result in solved.values())
        assert all(len(solved[c.name].joints) == len(c.joint_names) for c in chains)


def _planar_arm(tmp_path, *, second=(0.0, 0.5), first=(-0.1, 0.1)):
    tmp_path.mkdir(parents=True, exist_ok=True)
    urdf = tmp_path / "planar.urdf"
    urdf.write_text(f'''<robot name="planar">
      <link name="base"><inertial><mass value="1"/></inertial></link>
      <link name="upper"><inertial><mass value="1"/></inertial></link>
      <link name="lower"><inertial><mass value="1"/></inertial></link>
      <link name="hand"><inertial><mass value="1"/></inertial></link>
      <joint name="shoulder" type="revolute"><parent link="base"/><child link="upper"/><axis xyz="0 0 1"/>
        <limit lower="{first[0]}" upper="{first[1]}" effort="1" velocity="1"/></joint>
      <joint name="elbow" type="revolute"><parent link="upper"/><child link="lower"/><origin xyz="0.5 0 0"/>
        <axis xyz="0 0 1"/><limit lower="{second[0]}" upper="{second[1]}" effort="1" velocity="1"/></joint>
      <joint name="wrist" type="fixed"><parent link="lower"/><child link="hand"/><origin xyz="0.5 0 0"/></joint>
    </robot>''')
    usd = kinematic_usd(urdf, tmp_path / "planar.usda")
    spec = kinematics.ArmSpec("arm", "base", "hand", ("shoulder", "elbow"), np.eye(4), {}, {"shoulder": 0.0, "elbow": 0.2})
    return kinematics.arm_chain(usd, spec)


def test_a_target_reached_only_outside_the_limits_names_the_joint_limit(tmp_path):
    chain = _planar_arm(tmp_path)
    q = np.array([0.0, -1.0])
    unlimited = _planar_arm(tmp_path / "free", second=(-3.0, 3.0), first=(-3.0, 3.0))
    target = kinematics.forward(unlimited, q).tcp
    result = kinematics.solve(chain, target, orientation_weight_m=0.0)
    assert (result.ok, result.failure, result.detail) == (False, "ik_joint_limit", "found_only_outside_joint_limits")
    assert chain.lower[1] <= result.joints[1] <= chain.upper[1]
    # Within reach, but no start reaches it even with the limits off: the planar arm cannot leave its plane.
    lifted = target.copy()
    lifted[2, 3] = 0.3
    missed = kinematics.solve(unlimited, lifted, orientation_weight_m=0.0)
    assert (missed.failure, missed.detail) == ("ik_unreachable", "no_solution_from_seeds")
