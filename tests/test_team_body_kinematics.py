def _urdf_frames(urdf: Path, values: dict) -> dict:
    """Every URDF link's full pose from the independent source reader."""
    model = _parse_urdf(urdf)
    poses = {model["base_frame"]: np.eye(4)}
    for joint in model["joints"]:
        motion = np.eye(4)
        value = float(values.get(joint["name"], 0.0))
        if joint["type"] in {"revolute", "continuous"}:
            motion = _axis_rotation(joint["axis"], value)
        elif joint["type"] == "prismatic":
            motion[:3, 3] = np.asarray(joint["axis"]) / np.linalg.norm(joint["axis"]) * value
        poses[joint["child"]] = poses[joint["parent"]] @ joint["origin"] @ motion
    return poses


def _angle(a, b):
    return math.acos(max(-1.0, min(1.0, (float(np.trace(a[:3, :3].T @ b[:3, :3])) - 1.0) / 2.0)))


def _random_joints(chain, generator, count):
    low = np.where(np.isfinite(chain.lower), chain.lower, -math.pi)
    high = np.where(np.isfinite(chain.upper), chain.upper, math.pi)
    return low + (high - low) * generator.random((count, len(low)))


def _source(manifest_name, config):
    """The URDF name a bound manifest name (a prim name in the model) came from."""
    return config["usd_source_names"].get(manifest_name, manifest_name)


