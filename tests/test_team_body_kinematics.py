def test_clearance_names_the_link_and_stays_a_lower_bound(tmp_path):
    usd, chain = _boxed_arm(tmp_path)
    bounds = kinematics.link_bounds(usd, chain, hand_exclude=("pad",))
    q = np.zeros(2)
    world = np.eye(4)
    world[:3, 3] = [1.0, 2.0, 0.0]
    # A wall 5 cm beyond the upper link's +x face at mid height.
    wall = kinematics.OrientedBox.from_pose([1.0 + .04 + .05 + .01, 2.0, .3], [0, 0, 0, 1], [.01, .5, .5])
    report = kinematics.clearance(chain, bounds, q, world_from_base=world, boxes=[wall], margin_m=0.02)
    assert report["link"] == "upper" and report["obstacle"] == "box:0"
    assert report["minimum_clearance_m"] == pytest.approx(0.05, abs=1e-4) and not report["colliding"]
    assert report["unassessed_links"] == {"sensor": "link_geometry_missing"} and "base" not in report["per_link"]
    # Turned 90 degrees about the shoulder the arm lies along +x and passes through the wall.
    struck = kinematics.clearance(chain, bounds, [math.pi / 2, 0], world_from_base=world, boxes=[wall])
    assert struck["colliding"] and struck["minimum_clearance_m"] < 0 and struck["link"] in {"upper", "flange", "hand"}
    # Points: 3 cm above the flange's top face, and a SceneObstacles-like lookup gives the same answer.
    top = world @ np.array([0, 0, .1 + .4 + .04 + .03 + .03 + .03, 1.0])
    points = np.array([top[:3], [50.0, 50.0, 50.0]])
    report = kinematics.clearance(chain, bounds, q, world_from_base=world, points=points)
    assert report["link"] == "hand" and report["minimum_clearance_m"] == pytest.approx(0.03, abs=1e-4)

    class Lookup:
        def near(self, centre, radius):
            return points[np.linalg.norm(points - centre, axis=1) <= radius]

    assert kinematics.clearance(chain, bounds, q, world_from_base=world, points=Lookup()) == report
    nothing = kinematics.clearance(chain, bounds, q, world_from_base=world, points=points[1:])
    assert nothing["minimum_clearance_m"] is None and not nothing["colliding"]
    assert nothing["claim_ceiling"] == "cpu_bounded_estimate" and nothing["simulator_executed"] is False


