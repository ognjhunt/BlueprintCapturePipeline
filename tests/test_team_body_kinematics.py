def test_general_usd_physics_frames_reversed_joints_and_centimetre_stages(tmp_path):
    """Joint frames on both ends, a joint authored child-to-parent, Y axes and a centimetre stage."""
    from pxr import Gf, Usd, UsdGeom, UsdPhysics

    stage = Usd.Stage.CreateInMemory()
    UsdGeom.SetStageMetersPerUnit(stage, 0.01)
    stage.SetDefaultPrim(stage.DefinePrim("/robot", "Xform"))
    for name, z in (("base", 0.0), ("upper", 30.0), ("lower", 60.0)):
        prim = UsdGeom.Xform.Define(stage, f"/robot/{name}")
        prim.AddTranslateOp().Set(Gf.Vec3d(0, 0, z))
        UsdPhysics.RigidBodyAPI.Apply(prim.GetPrim())
    turn = Gf.Quatf(Gf.Rotation(Gf.Vec3d(1, 0, 0), 90).GetQuat())  # joint frame z -> body -y
    anchor = UsdPhysics.FixedJoint.Define(stage, "/robot/anchor")
    anchor.CreateBody1Rel().SetTargets(["/robot/base"])
    first = UsdPhysics.RevoluteJoint.Define(stage, "/robot/first")
    first.CreateBody0Rel().SetTargets(["/robot/base"])
    first.CreateBody1Rel().SetTargets(["/robot/upper"])
    first.CreateAxisAttr("Y")
    first.CreateLocalPos0Attr(Gf.Vec3f(0, 0, 30))
    first.CreateLocalPos1Attr(Gf.Vec3f(0, 0, 0))
    first.CreateLowerLimitAttr(-90.0)
    first.CreateUpperLimitAttr(90.0)
    second = UsdPhysics.RevoluteJoint.Define(stage, "/robot/second")  # authored from the child to the parent
    second.CreateBody0Rel().SetTargets(["/robot/lower"])
    second.CreateBody1Rel().SetTargets(["/robot/upper"])
    second.CreateAxisAttr("Z")
    second.CreateLocalPos0Attr(Gf.Vec3f(0, 0, 0))
    second.CreateLocalRot0Attr(turn)
    second.CreateLocalPos1Attr(Gf.Vec3f(0, 0, 30))
    second.CreateLocalRot1Attr(turn)
