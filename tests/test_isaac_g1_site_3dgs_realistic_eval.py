def _write_gaussian_ply(path: Path) -> None:
    path.write_text(
        "\n".join(
            [
                "ply",
                "format ascii 1.0",
                "comment Generated by splat-transform",
                "element vertex 2",
                "property float x",
                "property float y",
                "property float z",
                "property float scale_0",
                "property float rot_0",
                "property float opacity",
                "end_header",
                "0 0 0 1 0 1",
                "1 0 0 1 0 1",
            ]
        )
        + "\n",
        encoding="utf-8",
    )


