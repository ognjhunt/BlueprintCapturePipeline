def test_provider_entrypoint_writes_runtime_result_after_isaac_process_crash(
    tmp_path: Path,
) -> None:
    provider_dir = tmp_path / "provider_runtime"
    output_dir = tmp_path / "runtime_output"
    provider_dir.mkdir(parents=True)
    fake_isaac = tmp_path / "fake_isaac_python.sh"
    entrypoint = provider_dir / "run_isaac_realistic_runtime.sh"
    runner = provider_dir / "isaac_realistic_runtime_runner.py"
    manifest = provider_dir / "isaac_provider_eval_manifest.json"

    runner.write_text("raise SystemExit('runner should be simulated by fake isaac')\n")
    manifest.write_text("{}\n")
    fake_isaac.write_text(
        "#!/usr/bin/env bash\n"
        "out=''\n"
        "while [ \"$#\" -gt 0 ]; do\n"
        "  if [ \"$1\" = '--output-dir' ]; then shift; out=\"$1\"; fi\n"
        "  shift || true\n"
        "done\n"
        "mkdir -p \"$out\"\n"
        "printf '{\"phase\":\"runner_referencing_official_g1\",\"status\":\"running\"}\\n' > \"$out/isaac_runtime_phase_log.jsonl\"\n"
        "exit 139\n",
        encoding="utf-8",
    )
    entrypoint.write_text(_provider_entrypoint_source(), encoding="utf-8")
    fake_isaac.chmod(0o755)
    entrypoint.chmod(0o755)

    import os
    import subprocess

    env = {
        **os.environ,
        "BLUEPRINT_ISAAC_PYTHON": str(fake_isaac),
        "BLUEPRINT_ISAAC_EVAL_MANIFEST": str(manifest),
        "BLUEPRINT_ISAAC_OUTPUT_DIR": str(output_dir),
    }
    completed = subprocess.run(
        ["bash", str(entrypoint)],
        check=False,
        capture_output=True,
        text=True,
        env=env,
    )

