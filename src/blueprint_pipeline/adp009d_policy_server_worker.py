"""Start the policy server and prove its identity-bound control plane is ready.

A listening socket is not readiness.  One shipped server in this repo writes
``model_loaded_ready_to_serve`` before it calls ``serve_forever``, so a port
check would report a server that cannot yet serve.  Loading a 12.4 GB checkpoint
also takes far longer than binding a port, and an episode that starts too early
fails in a way that looks like a policy problem rather than a startup race.

Readiness here means a completed transport handshake plus exact server identity
and modality validation.  It deliberately sends no observation and requests no
action: a synthetic readiness inference would advance policy RNG/history before
the first retained episode observation.  Action shape and finite-value checks
therefore remain at the episode boundary, where the queried observation is
already sealed.

Runs under the policy venv's interpreter, never Isaac's.
"""

from __future__ import annotations

import hashlib
import json
import os
import queue
import re
import signal
import subprocess
import sys
import threading
import time
from pathlib import Path
from collections.abc import Mapping
from typing import Any

try:  # repository package
    from blueprint_pipeline.native_task_isaaclab_launch import (
        NATIVE_TASK_ARENA_DEVICE,
    )
except ModuleNotFoundError:  # flat provider-bundle layout
    # The provisioning script is generated by the repository package and
    # exports the shared launcher constant before this flat worker starts.
    # Refuse a missing binding rather than duplicate the device literal here.
    NATIVE_TASK_ARENA_DEVICE = os.environ[
        "BLUEPRINT_NATIVE_TASK_ARENA_DEVICE"
    ]

SCHEMA_VERSION = "adp009d_policy_server_worker.v2"

DEFAULT_HOST = "127.0.0.1"
DEFAULT_PORT = 8000
# Loading 12.4 GB of weights dominates this; a port appears long before.
READINESS_TIMEOUT_SECONDS = 900.0
READINESS_POLL_SECONDS = 10.0
# A readiness deadline is meaningless if one import, client constructor, ping,
# or metadata call can occupy the polling thread forever.  This bound is shorter
# than the overall model-load allowance and leaves the outer loop free to
# observe process exit and its own deadline.
# Identity/modality handshakes should be much cheaper than inference, while
# model loading can still delay the first successful metadata response. Keep a
# bounded attempt so a vendor client constructor cannot starve the outer
# readiness deadline.
HANDSHAKE_ATTEMPT_TIMEOUT_SECONDS = 120.0
SERVER_LOG_TAIL_BYTES = 32_768
FAILED_SERVER_TERMINATE_TIMEOUT_SECONDS = 10.0
READY_SERVER_TERMINATE_TIMEOUT_SECONDS = 10.0

TRANSPORT_OPENPI_WEBSOCKET = "openpi_websocket"
TRANSPORT_GROOT_ZMQ = "groot_zmq"
GROOT_DROID_EMBODIMENT_TAG = "OXE_DROID_RELATIVE_EEF_RELATIVE_JOINT"

# Read from each vendor runtime rather than assumed: openpi serves over a
# websocket on 8000 via scripts/serve_policy.py, while GR00T's client is
# gr00t.policy.server_client.PolicyClient over ZMQ, defaulting to 5555.  They
# share neither a transport nor a launch command, so a single hardcoded form
# can only ever serve one of them.
CANDIDATE_TRANSPORTS = {
    "pi05_droid": TRANSPORT_OPENPI_WEBSOCKET,
    "groot_n17_droid": TRANSPORT_GROOT_ZMQ,
    "groot_n16_droid": TRANSPORT_GROOT_ZMQ,
    "cosmos3_edge_policy_droid": TRANSPORT_OPENPI_WEBSOCKET,
}
CANDIDATE_DEFAULT_PORTS = {
    TRANSPORT_OPENPI_WEBSOCKET: 8000,
    TRANSPORT_GROOT_ZMQ: 5555,
}


class HandshakeAttemptTimeout(TimeoutError):
    """One readiness attempt starved the poll loop past its own bound."""


def transport_for(candidate_id: str) -> str:
    if candidate_id not in CANDIDATE_TRANSPORTS:
        raise RuntimeError(f"policy_server_unknown_candidate:{candidate_id}")
    return CANDIDATE_TRANSPORTS[candidate_id]


IDENTITY_BOUND_OPENPI_SERVER_MODULE = "openpi_droid_policy_runtime.py"


def build_serve_command(
    *,
    candidate_id: str,
    python: str,
    source_root: str,
    checkpoint_root: str,
    port: int,
    policy_spec_path: str | None = None,
    checkpoint_inventory_path: str | None = None,
    runtime_dir: str | Path | None = None,
    host: str = DEFAULT_HOST,
) -> list[str]:
    """The launch command for this candidate's own server.

    openpi's stock ``scripts/serve_policy.py`` publishes empty websocket
    metadata by design. The episode client is
    ``OpenPIWebsocketDroidPolicyClient``, whose ``__init__`` validates fourteen
    identity fields plus local checkpoint verification, so a stock server is
    refused *after* a full Isaac boot and scene build have been paid for. It is
    therefore not a server this lane can ever launch, and the fallback is
    removed rather than left as a trap.

    Instead we launch Blueprint's identity-bound wrapper around the same pinned
    upstream server, matching the pattern the cosmos lane already proved: a repo
    module that loads the unmodified official server class and serves it with
    verified identity metadata. Its spec comes from the same sealed execution
    spec the client validates against, so server and client cannot disagree.

    GR00T keeps its own launch: it shares neither transport nor CLI with openpi.
    """

    transport = transport_for(candidate_id)
    if transport == TRANSPORT_OPENPI_WEBSOCKET:
        missing = sorted(
            name
            for name, value in (
                ("policy_spec", policy_spec_path),
                ("checkpoint_inventory", checkpoint_inventory_path),
            )
            if not value
        )
        if missing:
            # Failing here is the point. The only other command that could be
            # produced is a stock server the episode is guaranteed to refuse.
            raise RuntimeError(
                "policy_server_identity_inputs_missing:" + ",".join(missing)
            )
        runtime = Path(runtime_dir) if runtime_dir else Path(__file__).resolve().parent
        return [
            python,
            str(runtime / IDENTITY_BOUND_OPENPI_SERVER_MODULE),
            "--policy-spec",
            str(policy_spec_path),
            "--checkpoint-dir",
            checkpoint_root,
            "--checkpoint-inventory",
            str(checkpoint_inventory_path),
            "--host",
            host,
            "--port",
            str(port),
        ]
    return [
        python,
        str(Path(source_root, "gr00t", "eval", "run_gr00t_server.py")),
        "--model-path",
        checkpoint_root,
        "--embodiment-tag",
        GROOT_DROID_EMBODIMENT_TAG,
        "--device",
        # one shared constant: this is the single place the policy server and
        # Isaac must agree about which card they co-reside on
        NATIVE_TASK_ARENA_DEVICE,
        "--host",
        DEFAULT_HOST,
        "--port",
        str(port),
    ]


