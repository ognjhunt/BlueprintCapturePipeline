def _counts_by_key(attempts: Sequence[Mapping[str, Any]], key: str) -> list[dict[str, Any]]:
    grouped: dict[str, dict[str, int]] = {}
    for attempt in attempts:
        value = _string(attempt.get(key)) or "unknown"
        row = grouped.setdefault(value, {"attempted": 0, "passed": 0, "failed": 0, "blocked": 0})
        row["attempted"] += 1
        if attempt.get("status") == "blocked":
            row["blocked"] += 1
        elif attempt.get("success"):
            row["passed"] += 1
        else:
            row["failed"] += 1
    return [{key: key_value, **counts} for key_value, counts in sorted(grouped.items())]


