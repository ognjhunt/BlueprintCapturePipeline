def _xy_clearance(point_xy: Sequence[float], proxy: Mapping[str, Any]) -> float | None:
    if proxy.get("collision_enabled") is not True or proxy.get("category") == "floor":
        return None
    if proxy.get("geom_type") != "box":
        return None
    pos = proxy.get("pos") or []
    size = proxy.get("size") or []
    if len(pos) < 2 or len(size) < 2:
        return None
    dx = max(abs(float(point_xy[0]) - float(pos[0])) - float(size[0]), 0.0)
    dy = max(abs(float(point_xy[1]) - float(pos[1])) - float(size[1]), 0.0)
    if dx == 0.0 and dy == 0.0:
        penetration_x = float(size[0]) - abs(float(point_xy[0]) - float(pos[0]))
        penetration_y = float(size[1]) - abs(float(point_xy[1]) - float(pos[1]))
        return -min(penetration_x, penetration_y) - ROBOT_RADIUS_M
    return math.hypot(dx, dy) - ROBOT_RADIUS_M


def _minimum_clearance(point_xy: Sequence[float], proxies: Sequence[Mapping[str, Any]]) -> tuple[float, str | None]:
    values: list[tuple[float, str]] = []
    for proxy in proxies:
        clearance = _xy_clearance(point_xy, proxy)
        if clearance is None:
            continue
        values.append((clearance, _string(proxy.get("proxy_id"))))
    if not values:
        return (999.0, None)
    return min(values, key=lambda item: item[0])


def _planner_bounds(task: Mapping[str, Any], proxies: Sequence[Mapping[str, Any]] | None) -> tuple[float, float, float, float]:
    bounds = task.get("route_planner_bounds")
    if (
        isinstance(bounds, Mapping)
        and all(key in bounds for key in ("x_min", "x_max", "y_min", "y_max"))
    ):
        return (
            float(bounds["x_min"]),
            float(bounds["x_max"]),
            float(bounds["y_min"]),
            float(bounds["y_max"]),
        )
    for proxy in proxies or []:
        if proxy.get("category") == "floor" and proxy.get("geom_type") == "plane":
            pos = proxy.get("pos") or [0.0, 0.0, 0.0]
            size = proxy.get("size") or [3.0, 3.0, 0.05]
            return (
                float(pos[0]) - float(size[0]),
                float(pos[0]) + float(size[0]),
                float(pos[1]) - float(size[1]),
                float(pos[1]) + float(size[1]),
            )
    return (-3.5, 3.5, -6.5, 6.5)


def _clip_xy(point: Sequence[float], bounds: tuple[float, float, float, float]) -> list[float]:
    x_min, x_max, y_min, y_max = bounds
    return [
        min(max(float(point[0]), x_min + 0.15), x_max - 0.15),
        min(max(float(point[1]), y_min + 0.15), y_max - 0.15),
    ]


def _snap_to_clear_point(
    point: Sequence[float],
    *,
    proxies: Sequence[Mapping[str, Any]],
    bounds: tuple[float, float, float, float],
    min_clearance: float,
    grid_step: float = 0.35,
    max_radius_m: float = 3.0,
) -> list[float]:
    base = _clip_xy(point, bounds)
    candidates: list[tuple[float, float, float]] = []
    max_cells = int(max_radius_m / grid_step)
    for ix in range(-max_cells, max_cells + 1):
        for iy in range(-max_cells, max_cells + 1):
            x = base[0] + ix * grid_step
            y = base[1] + iy * grid_step
            if not (bounds[0] + 0.15 <= x <= bounds[1] - 0.15 and bounds[2] + 0.15 <= y <= bounds[3] - 0.15):
                continue
            distance = math.hypot(x - base[0], y - base[1])
            candidates.append((distance, x, y))
    candidates.sort(key=lambda item: item[0])
    best = base
    best_clearance = -999.0
    for _distance, x, y in candidates:
        clearance, _nearest = _minimum_clearance([x, y], proxies)
        if clearance > best_clearance:
            best = [x, y]
            best_clearance = clearance
        if clearance >= min_clearance:
            return [round(x, 6), round(y, 6)]
    return [round(best[0], 6), round(best[1], 6)]


def _segment_min_clearance(
    first: Sequence[float],
    second: Sequence[float],
    proxies: Sequence[Mapping[str, Any]],
    *,
    samples: int = 12,
) -> float:
    min_clearance = 999.0
    for index in range(max(2, samples)):
        alpha = index / float(max(1, samples - 1))
        x = float(first[0]) + (float(second[0]) - float(first[0])) * alpha
        y = float(first[1]) + (float(second[1]) - float(first[1])) * alpha
        clearance, _nearest = _minimum_clearance([x, y], proxies)
        min_clearance = min(min_clearance, clearance)
    return min_clearance


def _route_min_clearance(route: Sequence[Sequence[float]], proxies: Sequence[Mapping[str, Any]]) -> float:
    if len(route) < 2:
        clearance, _nearest = _minimum_clearance(route[0][:2], proxies)
        return clearance
    return min(
        _segment_min_clearance(first, second, proxies)
        for first, second in zip(route, route[1:])
    )


def _plan_clear_route(
    *,
    start: Sequence[float],
    target: Sequence[float],
    proxies: Sequence[Mapping[str, Any]],
    task: Mapping[str, Any],
    min_clearance: float,
) -> list[list[float]]:
    bounds = _planner_bounds(task, proxies)
    z = float(start[2]) if len(start) >= 3 else DEFAULT_ROOT_Z_M
    start_xy = _snap_to_clear_point(
        start,
        proxies=proxies,
        bounds=bounds,
        min_clearance=min_clearance,
    )
    target_xy = _snap_to_clear_point(
        target,
        proxies=proxies,
        bounds=bounds,
        min_clearance=min_clearance,
    )
    x_min, x_max, y_min, y_max = bounds
    lane_points = [
        [start_xy[0], target_xy[1]],
        [target_xy[0], start_xy[1]],
        [x_min + 0.75, start_xy[1]],
        [x_min + 0.75, target_xy[1]],
        [x_max - 0.75, start_xy[1]],
        [x_max - 0.75, target_xy[1]],
        [start_xy[0], y_min + 0.75],
        [target_xy[0], y_min + 0.75],
        [start_xy[0], y_max - 0.75],
        [target_xy[0], y_max - 0.75],
        [x_min + 0.75, y_min + 0.75],
        [x_min + 0.75, y_max - 0.75],
        [x_max - 0.75, y_min + 0.75],
        [x_max - 0.75, y_max - 0.75],
    ]
    clear_lanes = [
        _snap_to_clear_point(
            point,
            proxies=proxies,
            bounds=bounds,
            min_clearance=min_clearance,
        )
        for point in lane_points
    ]
    candidates: list[list[list[float]]] = [
        [[start_xy[0], start_xy[1], z], [target_xy[0], target_xy[1], z]]
    ]
    for point in clear_lanes:
        candidates.append(
            [[start_xy[0], start_xy[1], z], [point[0], point[1], z], [target_xy[0], target_xy[1], z]]
        )
    for first in clear_lanes:
        for second in clear_lanes:
            if first == second:
                continue
            candidates.append(
                [
                    [start_xy[0], start_xy[1], z],
                    [first[0], first[1], z],
                    [second[0], second[1], z],
                    [target_xy[0], target_xy[1], z],
                ]
            )
    best_route = candidates[0]
    best_clearance = -999.0
    best_distance = float("inf")
    for route in candidates:
        clearance = _route_min_clearance(route, proxies)
        distance = _route_distance(route)
        if clearance > best_clearance or (
            math.isclose(clearance, best_clearance, abs_tol=1e-6) and distance < best_distance
        ):
            best_route = route
            best_clearance = clearance
            best_distance = distance
    return best_route


def _route_points(
    spawn: Mapping[str, Any],
    task: Mapping[str, Any],
    proxies: Sequence[Mapping[str, Any]] | None = None,
) -> list[list[float]]:
    start = list(spawn.get("pose_xyz_yaw") or [0.0, 0.0, DEFAULT_ROOT_Z_M, 0.0])[:3]
    target = list(task.get("target_pose_xyz") or [0.0, 0.0, DEFAULT_ROOT_Z_M])[:3]
    if proxies and spawn.get("valid_for_execution") is not False:
        thresholds = dict(task.get("success_thresholds") or {})
        return _plan_clear_route(
            start=start,
            target=target,
            proxies=proxies,
            task=task,
            min_clearance=float(thresholds.get("minimum_clearance_m") or MIN_CLEARANCE_M),
        )
    preferred = task.get("preferred_route_waypoints")
    if isinstance(preferred, Sequence) and not isinstance(preferred, (str, bytes)):
        waypoints: list[list[float]] = []
        for point in preferred:
            if isinstance(point, Sequence) and not isinstance(point, (str, bytes)) and len(point) >= 2:
                waypoints.append(
                    [
                        float(point[0]),
                        float(point[1]),
                        float(point[2]) if len(point) >= 3 else float(start[2]),
                    ]
                )
        return [start, *waypoints, target]
    task_id = _string(task.get("task_id"))
    spawn_id = _string(spawn.get("spawn_id"))
    if task_id == "navigate_chalkboard_inspect":
        if spawn_id == "blocked_occluded_route_variant":
            return [start, [1.55, -0.45, start[2]], target]
        return [
            start,
            [-2.65, -1.45, start[2]],
            [-2.35, 1.45, start[2]],
            target,
        ]
    if task_id == "desk_object_contact_check":
        return [
            start,
            [-2.35, -1.15, start[2]],
            target,
        ]
    if task_id == "inspect_shelf_desk_zone":
        return [
            start,
            [2.80, -1.65, start[2]],
            target,
        ]
    if task_id == "clear_floor_obstruction_route" and spawn_id != "blocked_occluded_route_variant":
        return [
            start,
            [start[0], -1.65, start[2]],
            [2.90, -1.65, start[2]],
            target,
        ]
    if task_id == "carry_object_to_drop_zone":
        return [start, [-0.85, -0.18, start[2]], [0.85, -1.45, start[2]], target]
    return [start, target]


def _route_distance(points: Sequence[Sequence[float]]) -> float:
    distance = 0.0
    for first, second in zip(points, points[1:]):
        distance += math.dist([float(first[0]), float(first[1])], [float(second[0]), float(second[1])])
    return distance


def _interpolate_route(points: Sequence[Sequence[float]], alpha: float) -> tuple[list[float], float]:
    if len(points) <= 1:
        point = list(points[0])
        return [float(point[0]), float(point[1]), float(point[2])], 0.0
    distances = [
        math.dist([float(first[0]), float(first[1])], [float(second[0]), float(second[1])])
        for first, second in zip(points, points[1:])
    ]
    total = sum(distances)
    if total <= 0:
        point = list(points[-1])
        return [float(point[0]), float(point[1]), float(point[2])], 0.0
    remaining = max(0.0, min(1.0, alpha)) * total
    for index, segment_distance in enumerate(distances):
        if remaining <= segment_distance or index == len(distances) - 1:
            local_alpha = 0.0 if segment_distance <= 0 else remaining / segment_distance
            start = points[index]
            end = points[index + 1]
            x = float(start[0]) + (float(end[0]) - float(start[0])) * local_alpha
            y = float(start[1]) + (float(end[1]) - float(start[1])) * local_alpha
            z = float(start[2]) + (float(end[2]) - float(start[2])) * local_alpha
            yaw = math.atan2(float(end[1]) - float(start[1]), float(end[0]) - float(start[0]))
            return [x, y, z], yaw
        remaining -= segment_distance
    point = list(points[-1])  # pragma: no cover - loop always returns on its final segment.
    return [float(point[0]), float(point[1]), float(point[2])], 0.0  # pragma: no cover


def validate_spawns(
    *,
    spawns: Sequence[Mapping[str, Any]],
    proxies: Sequence[Mapping[str, Any]],
    generated_at: str,
) -> dict[str, Any]:
    rows = []
    for spawn in spawns:
        pose = list(spawn.get("pose_xyz_yaw") or [0.0, 0.0, DEFAULT_ROOT_Z_M, 0.0])
        clearance, nearest_proxy = _minimum_clearance(pose[:2], proxies)
        floor_contact = 0.55 <= float(pose[2]) <= 1.05
        blockers: list[str] = []
        if not floor_contact:
            blockers.append("spawn_floor_contact_not_in_expected_height_band")
        if clearance < MIN_CLEARANCE_M:
            blockers.append("spawn_clearance_below_threshold")
        if spawn.get("expected_invalid_reason") and spawn.get("expected_invalid_reason") not in blockers:
            blockers.append(_string(spawn.get("expected_invalid_reason")))
        rows.append(
            {
                **dict(spawn),
                "floor_contact_validated": floor_contact,
                "robot_clearance_validated": clearance >= MIN_CLEARANCE_M,
                "initial_collision_state": "blocked" if clearance < 0 else "clear",
                "minimum_clearance_m": round(clearance, 6),
                "nearest_collision_proxy_id": nearest_proxy,
                "task_reachability_precheck": "blocked" if blockers else "reachable",
                "valid_for_execution": not blockers,
                "blockers": blockers,
            }
        )
    return {
        "schema_version": SPAWN_VALIDATION_SCHEMA_VERSION,
        "generated_at": generated_at,
        "spawn_count": len(rows),
        "valid_spawn_count": sum(1 for row in rows if row["valid_for_execution"]),
        "invalid_spawn_count": sum(1 for row in rows if not row["valid_for_execution"]),
        "invalid_spawns_preserved_as_blocked_rows": True,
        "spawns": rows,
    }


