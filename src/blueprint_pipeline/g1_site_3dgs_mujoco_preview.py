def build_scene_proxies_from_metadata(
    *,
    labels_json: str | Path | None,
    structure_json: str | Path | None,
    occupancy_json: str | Path | None,
    max_label_proxies: int = 90,
) -> tuple[list[dict[str, Any]], dict[str, Any], dict[str, Any]]:
    occupancy = _load_json_mapping(occupancy_json)
    structure = _load_json_mapping(structure_json)
    labels = _load_json_list(labels_json)
    if not occupancy or not structure:
        return (
            _default_scene_proxies(),
            {
                "status": "fallback_default_proxy",
                "source": "generated_default_classroom_proxy",
                "blockers": ["metadata_occupancy_or_structure_missing"],
            },
            {},
        )
    origin_x, origin_y, transform = _metadata_origin(occupancy)
    proxies: list[dict[str, Any]] = []
    bounds = transform.get("local_bounds") or [[-3.0, -5.0], [3.0, 5.0]]
    lower, upper = bounds[0], bounds[1]
    floor_size = [
        max(1.0, (float(upper[0]) - float(lower[0])) / 2.0),
        max(1.0, (float(upper[1]) - float(lower[1])) / 2.0),
        0.05,
    ]
    proxies.append(
        {
            "proxy_id": "interiorgs_occupancy_floor",
            "label": "InteriorGS occupancy floor",
            "source": "interiorgs_occupancy_json",
            "geom_type": "plane",
            "pos": [0.0, 0.0, 0.0],
            "size": [round(floor_size[0], 6), round(floor_size[1], 6), 0.05],
            "rgba": [0.46, 0.47, 0.45, 1.0],
            "collision_enabled": True,
            "category": "floor",
        }
    )
    for index, wall in enumerate(structure.get("walls") or []):
        if isinstance(wall, Mapping):
            proxy = _wall_proxy_from_segment(
                wall,
                index=index,
                origin_x=origin_x,
                origin_y=origin_y,
            )
            if proxy is not None:
                proxies.append(proxy)
    label_proxies = [
        proxy
        for item in labels
        if (proxy := _proxy_from_label_item(item, origin_x=origin_x, origin_y=origin_y)) is not None
    ]
    label_proxies.sort(key=lambda item: float(item.get("volume_m3_estimate") or 0.0), reverse=True)
    selected_labels = []
    always_keep_markers = ("table", "chair", "shelf", "wardrobe", "reception", "stove", "trash", "barrel", "stool")
    for proxy in label_proxies:
        label = _string(proxy.get("source_label")).lower()
        if not proxy.get("collision_enabled"):
            continue
        if (
            any(marker in label for marker in always_keep_markers)
            or float(proxy.get("volume_m3_estimate") or 0.0) >= 0.04
        ):
            selected_labels.append(proxy)
        if len(selected_labels) >= max_label_proxies:
            break
    proxies.extend(selected_labels)
    anchors = _add_dataset_task_anchors(proxies, transform=transform)
    metadata_manifest = {
        "status": "completed",
        "source": "interiorgs_structure_labels_occupancy",
        "coordinate_transform": transform,
        "structure_wall_count": len(structure.get("walls") or []),
        "structure_hole_count": len(structure.get("holes") or []),
        "label_instance_count": len(labels),
        "selected_label_proxy_count": len(selected_labels),
        "proxy_count": len(proxies),
        "max_label_proxies": max_label_proxies,
        "task_anchors": anchors,
        "proof_boundary": (
            "Colliders are derived from InteriorGS structure wall segments and labeled 3D "
            "bounding boxes, plus generated task anchors for requested evaluation semantics "
            "that are not present as labels. This is metadata-derived collision proxy truth, "
            "not direct Gaussian splat surface physics."
        ),
    }
    return proxies, metadata_manifest, anchors


def _box_mesh(
    *,
    center: Sequence[float],
    half_size: Sequence[float],
) -> tuple[list[tuple[float, float, float]], list[tuple[int, int, int]]]:
    cx, cy, cz = [float(value) for value in center[:3]]
    hx, hy, hz = [max(0.005, float(value)) for value in half_size[:3]]
    vertices = [
        (cx - hx, cy - hy, cz - hz),
        (cx + hx, cy - hy, cz - hz),
        (cx + hx, cy + hy, cz - hz),
        (cx - hx, cy + hy, cz - hz),
        (cx - hx, cy - hy, cz + hz),
        (cx + hx, cy - hy, cz + hz),
        (cx + hx, cy + hy, cz + hz),
        (cx - hx, cy + hy, cz + hz),
    ]
    faces = [
        (1, 2, 3),
        (1, 3, 4),
        (5, 8, 7),
        (5, 7, 6),
        (1, 5, 6),
        (1, 6, 2),
        (2, 6, 7),
        (2, 7, 3),
        (3, 7, 8),
        (3, 8, 4),
        (4, 8, 5),
        (4, 5, 1),
    ]
    return vertices, faces


def _write_proxy_scene_obj(path: Path, proxies: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    ensure_dir(path.parent)
    lines = [
        "# Blueprint generated classroom/interior proxy mesh",
        "# Collision scoring uses MJCF primitive geoms; this OBJ is visual/review geometry.",
    ]
    vertex_offset = 0
    object_count = 0
    face_count = 0
    vertex_count = 0
    for proxy in proxies:
        geom_type = _string(proxy.get("geom_type")) or "box"
        if geom_type not in {"box", "plane"}:
            continue
        pos = list(proxy.get("pos") or [0.0, 0.0, 0.0])
        size = list(proxy.get("size") or [1.0, 1.0, 1.0])
        if len(pos) < 3 or len(size) < 3:
            continue
        if geom_type == "plane":
            center = [float(pos[0]), float(pos[1]), -0.01]
            half_size = [float(size[0]), float(size[1]), 0.01]
        else:
            center = [float(pos[0]), float(pos[1]), float(pos[2])]
            half_size = [float(size[0]), float(size[1]), float(size[2])]
        vertices, faces = _box_mesh(center=center, half_size=half_size)
        lines.append(f"o {_safe_id(proxy.get('proxy_id'), fallback=f'proxy_{object_count:03d}')}")
        lines.extend(f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in vertices)
        for face in faces:
            shifted = [index + vertex_offset for index in face]
            lines.append("f " + " ".join(str(index) for index in shifted))
        vertex_offset += len(vertices)
        vertex_count += len(vertices)
        face_count += len(faces)
        object_count += 1
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {
        "status": "completed" if object_count else "blocked",
        "path": str(path),
        "object_count": object_count,
        "vertex_count": vertex_count,
        "face_count": face_count,
        "size_bytes": path.stat().st_size if path.is_file() else 0,
        "sha256": _sha256(path) if path.is_file() else None,
        "format": "obj",
        "source": "generated_structured_classroom_proxy",
        "proof_boundary": (
            "Generated proxy OBJ approximates classroom fixtures for review/rendering. "
            "MuJoCo scoring uses explicit MJCF primitive colliders from the same proxy plan."
        ),
    }


def _attempt_visual_asset_mesh_conversion(
    *,
    ply_asset: str | Path,
    spz_asset: str | Path,
    output_dir: Path,
    ply_inspection: Mapping[str, Any],
    spz_inspection: Mapping[str, Any],
) -> list[dict[str, Any]]:
    ensure_dir(output_dir)
    attempts: list[dict[str, Any]] = []
    ply_path = Path(ply_asset).expanduser().resolve()
    ply_header = dict(ply_inspection.get("ply_header") or {})
    if not ply_path.is_file():
        attempts.append(
            {
                "source": str(ply_path),
                "target_format": "obj",
                "status": "blocked",
                "blocker": "source_ply_missing",
            }
        )
    elif not ply_header.get("has_face_element"):
        attempts.append(
            {
                "source": str(ply_path),
                "target_format": "obj",
                "status": "blocked",
                "blocker": "source_ply_has_no_triangle_faces",
                "reason": (
                    "This PLY appears to be Gaussian splat/point data. A truthful OBJ export "
                    "requires surface reconstruction, not a direct format conversion."
                ),
                "source_vertex_count": ply_header.get("vertex_count"),
                "source_face_count": ply_header.get("face_count"),
            }
        )
    else:
        target = output_dir / f"{ply_path.stem}.obj"
        try:
            import trimesh  # type: ignore[import-not-found]

            mesh = trimesh.load(str(ply_path), force="mesh")
            if not getattr(mesh, "faces", None).size:
                raise ValueError("trimesh_load_produced_no_faces")
            mesh.export(str(target))
            attempts.append(
                {
                    "source": str(ply_path),
                    "target_format": "obj",
                    "target": str(target),
                    "status": "completed",
                    "face_count": int(len(mesh.faces)),
                    "vertex_count": int(len(mesh.vertices)),
                    "sha256": _sha256(target),
                }
            )
        except Exception as exc:
            attempts.append(
                {
                    "source": str(ply_path),
                    "target_format": "obj",
                    "status": "blocked",
                    "blocker": "ply_mesh_to_obj_conversion_failed",
                    "error": str(exc)[:500],
                }
            )
    spz_path = Path(spz_asset).expanduser().resolve()
    attempts.append(
        {
            "source": str(spz_path),
            "target_format": "obj",
            "status": "blocked",
            "blocker": "spz_surface_reconstruction_runtime_not_available",
            "reason": (
                "SPZ is preserved as browser/viewer visual media. This repo has no local "
                "SPZ-to-triangle-surface reconstruction runtime, so a direct OBJ/MSH export "
                "would not be a truthful collision mesh."
            ),
            "source_exists": bool(spz_inspection.get("exists")),
            "source_size_bytes": spz_inspection.get("size_bytes"),
        }
    )
    attempts.append(
        {
            "source": str(spz_path),
            "target_format": "msh",
            "status": "blocked",
            "blocker": "no_local_mujoco_msh_writer_for_spz_or_gaussian_splat_surface",
            "reason": (
                "A MuJoCo-compatible MSH would still require real triangle geometry first. "
                "The generated proxy OBJ/MJCF path is used instead."
            ),
        }
    )
    return attempts


