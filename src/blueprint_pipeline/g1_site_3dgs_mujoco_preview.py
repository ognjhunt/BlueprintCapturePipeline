def _string(value: Any) -> str:
    return str(value).strip() if value is not None else ""


def _safe_id(value: Any, *, fallback: str = "item") -> str:
    text = _string(value) or fallback
    cleaned = "".join(character.lower() if character.isalnum() else "_" for character in text)
    return "_".join(part for part in cleaned.split("_") if part) or fallback


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _xml_escape(value: Path | str) -> str:
    return str(value).replace("&", "&amp;").replace('"', "&quot;")


def _quat_yaw(yaw: float) -> list[float]:
    return [math.cos(yaw / 2.0), 0.0, 0.0, math.sin(yaw / 2.0)]


def _read_ply_header(path: Path, *, max_bytes: int = 2_000_000) -> dict[str, Any]:
    data = path.read_bytes()[:max_bytes]
    marker = b"end_header"
    end = data.find(marker)
    if end < 0:
        return {"status": "blocked", "blocker": "ply_header_end_not_found"}
    header_bytes = data[: end + len(marker)]
    header = header_bytes.decode("utf-8", errors="replace")
    lines = [line.strip() for line in header.splitlines() if line.strip()]
    elements: list[dict[str, Any]] = []
    current: dict[str, Any] | None = None
    comments: list[str] = []
    properties: list[str] = []
    for line in lines:
        if line.startswith("comment "):
            comments.append(line[8:])
        elif line.startswith("element "):
            _, name, count = (line.split(maxsplit=2) + ["0"])[:3]
            current = {"name": name, "count": int(count) if count.isdigit() else count, "properties": []}
            elements.append(current)
        elif line.startswith("property "):
            properties.append(line)
            if current is not None:
                current["properties"].append(line)
    face_element = next((item for item in elements if item.get("name") == "face"), None)
    vertex_element = next((item for item in elements if item.get("name") == "vertex"), None)
    lower_header = header.lower()
    gaussian_markers = (
        "splat",
        "scale_0",
        "rot_0",
        "f_dc_0",
        "opacity",
        "generated by splat",
    )
    return {
        "status": "inspected",
        "format": next((line for line in lines if line.startswith("format ")), None),
        "header_byte_count": len(header_bytes),
        "comments": comments[:20],
        "elements": elements,
        "vertex_count": vertex_element.get("count") if vertex_element else None,
        "face_count": face_element.get("count") if face_element else 0,
        "has_face_element": bool(face_element and int(face_element.get("count") or 0) > 0),
        "gaussian_splat_markers": [marker for marker in gaussian_markers if marker in lower_header],
        "appears_gaussian_splat_payload": any(marker in lower_header for marker in gaussian_markers)
        and not bool(face_element and int(face_element.get("count") or 0) > 0),
        "properties_sample": properties[:40],
    }


def inspect_scene_asset(path: str | Path) -> dict[str, Any]:
    """Inspect a visual source asset without claiming it is MuJoCo-compatible."""

    resolved = Path(path).expanduser().resolve()
    payload: dict[str, Any] = {
        "path": str(resolved),
        "exists": resolved.is_file(),
        "extension": resolved.suffix.lower(),
        "mujoco_direct_collision_mesh_supported": False,
    }
    if not resolved.is_file():
        return {**payload, "status": "missing", "blockers": ["asset_missing"]}

    prefix = resolved.read_bytes()[:64]
    payload.update(
        {
            "status": "inspected",
            "size_bytes": resolved.stat().st_size,
            "sha256": _sha256(resolved),
            "first_64_bytes_hex": prefix.hex(),
        }
    )
    if resolved.suffix.lower() == ".ply":
        header = _read_ply_header(resolved)
        payload.update(
            {
                "asset_kind": "gaussian_ply"
                if header.get("appears_gaussian_splat_payload")
                else "ply_mesh_or_point_cloud",
                "ply_header": header,
                "mujoco_direct_collision_mesh_supported": False,
                "mujoco_collision_blocker": "mujoco_3_9_probe_no_ply_mesh_decoder",
            }
        )
    elif resolved.suffix.lower() == ".spz":
        payload.update(
            {
                "asset_kind": "spz",
                "gzip_magic_present": prefix.startswith(b"\x1f\x8b"),
                "mujoco_direct_collision_mesh_supported": False,
                "mujoco_collision_blocker": "mujoco_3_9_probe_no_spz_mesh_decoder",
            }
        )
    else:
        payload.update(
            {
                "asset_kind": resolved.suffix.lower().lstrip(".") or "unknown",
                "mujoco_collision_blocker": "not_a_required_3dgs_site_asset",
            }
        )
    return payload


def inspect_optional_scene_metadata(path: str | Path | None, *, metadata_kind: str) -> dict[str, Any]:
    if not path:
        return {
            "metadata_kind": metadata_kind,
            "status": "not_provided",
            "path": None,
        }
    resolved = Path(path).expanduser().resolve()
    payload: dict[str, Any] = {
        "metadata_kind": metadata_kind,
        "path": str(resolved),
        "exists": resolved.is_file(),
        "extension": resolved.suffix.lower(),
    }
    if not resolved.is_file():
        return {**payload, "status": "missing", "blockers": ["metadata_file_missing"]}
    payload.update(
        {
            "status": "inspected",
            "size_bytes": resolved.stat().st_size,
            "sha256": _sha256(resolved),
        }
    )
    if resolved.suffix.lower() == ".json":
        try:
            data = json.loads(resolved.read_text(encoding="utf-8"))
            if isinstance(data, Mapping):
                keys = sorted(str(key) for key in data.keys())
                payload.update(
                    {
                        "json_top_level_type": "object",
                        "top_level_keys": keys[:80],
                        "top_level_key_count": len(keys),
                    }
                )
                for key in ("objects", "labels", "rooms", "walls", "floors", "instances"):
                    value = data.get(key)
                    if isinstance(value, Sequence) and not isinstance(value, (str, bytes, bytearray)):
                        payload[f"{key}_count"] = len(value)
            elif isinstance(data, list):
                first = data[0] if data else {}
                label_counts: dict[str, int] = {}
                if isinstance(first, Mapping):
                    for item in data:
                        if isinstance(item, Mapping) and _string(item.get("label")):
                            label = _string(item.get("label"))
                            label_counts[label] = label_counts.get(label, 0) + 1
                payload.update(
                    {
                        "json_top_level_type": "array",
                        "item_count": len(data),
                        "first_item_keys": sorted(str(key) for key in first.keys())[:40]
                        if isinstance(first, Mapping)
                        else [],
                        "label_counts": dict(sorted(label_counts.items())),
                    }
                )
            else:
                payload.update({"json_top_level_type": type(data).__name__})
        except Exception as exc:
            payload.update(
                {
                    "status": "blocked",
                    "blockers": ["metadata_json_parse_failed"],
                    "error": str(exc)[:500],
                }
            )
    elif resolved.suffix.lower() in {".png", ".jpg", ".jpeg"}:
        try:
            from PIL import Image

            with Image.open(resolved) as image:
                payload.update(
                    {
                        "image_width": int(image.width),
                        "image_height": int(image.height),
                        "image_mode": image.mode,
                    }
                )
        except Exception as exc:
            payload.update(
                {
                    "status": "blocked",
                    "blockers": ["metadata_image_parse_failed"],
                    "error": str(exc)[:500],
                }
            )
    else:
        payload["blockers"] = ["metadata_format_not_used_by_current_proxy_generator"]
    return payload


def _probe_mujoco_mesh_support(output_dir: Path) -> dict[str, Any]:
    try:
        import mujoco  # type: ignore[import-not-found]
    except Exception as exc:  # pragma: no cover - environment dependent.
        return {
            "status": "blocked",
            "blocker": "mujoco_import_failed",
            "error": str(exc),
        }

    probe_dir = output_dir / "mujoco_mesh_support_probe"
    ensure_dir(probe_dir)
    cube_obj = probe_dir / "cube.obj"
    cube_obj.write_text(
        "\n".join(
            [
                "v -0.5 -0.5 -0.5",
                "v 0.5 -0.5 -0.5",
                "v 0.5 0.5 -0.5",
                "v -0.5 0.5 -0.5",
                "v -0.5 -0.5 0.5",
                "v 0.5 -0.5 0.5",
                "v 0.5 0.5 0.5",
                "v -0.5 0.5 0.5",
                "f 1 2 3",
                "f 1 3 4",
                "f 5 8 7",
                "f 5 7 6",
                "f 1 5 6",
                "f 1 6 2",
                "f 2 6 7",
                "f 2 7 3",
                "f 3 7 8",
                "f 3 8 4",
                "f 4 8 5",
                "f 4 5 1",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    triangle_ply = probe_dir / "triangle.ply"
    triangle_ply.write_text(
        "\n".join(
            [
                "ply",
                "format ascii 1.0",
                "element vertex 3",
                "property float x",
                "property float y",
                "property float z",
                "element face 1",
                "property list uchar int vertex_indices",
                "end_header",
                "0 0 0",
                "1 0 0",
                "0 1 0",
                "3 0 1 2",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    spz = probe_dir / "visual.spz"
    spz.write_bytes(b"SPZ\x00not-a-mujoco-mesh")
    cases = {"obj_cube": cube_obj, "ply_triangle": triangle_ply, "spz_visual": spz}
    results: dict[str, Any] = {}
    for case, mesh_path in cases.items():
        xml_path = probe_dir / f"{case}.xml"
        xml_path.write_text(
            (
                '<mujoco><asset><mesh name="m" file="'
                + _xml_escape(mesh_path.name)
                + '"/></asset><worldbody><geom type="mesh" mesh="m"/></worldbody></mujoco>'
            ),
            encoding="utf-8",
        )
        try:
            model = mujoco.MjModel.from_xml_path(str(xml_path))
            results[case] = {"loaded": True, "mesh_count": int(model.nmesh)}
        except Exception as exc:
            results[case] = {
                "loaded": False,
                "error": str(exc).splitlines()[0][:400],
            }
    return {
        "status": "completed",
        "mujoco_version": getattr(mujoco, "__version__", None),
        "mujoco_module_file": getattr(mujoco, "__file__", None),
        "probe_results": results,
        "conclusion": (
            "Installed MuJoCo loads OBJ triangle meshes but does not provide a PLY or SPZ "
            "mesh decoder in this environment; 3DGS/SPZ inputs must remain visual sources "
            "or be converted into a real mesh/proxy before collision scoring."
        ),
    }


