def _wall_proxy_from_segment(
    wall: Mapping[str, Any],
    *,
    index: int,
    origin_x: float,
    origin_y: float,
) -> dict[str, Any] | None:
    location = wall.get("location")
    if (
        not isinstance(location, Sequence)
        or isinstance(location, (str, bytes))
        or len(location) < 2
    ):
        return None
    first = location[0]
    second = location[1]
    if not (
        isinstance(first, Sequence)
        and not isinstance(first, (str, bytes))
        and isinstance(second, Sequence)
        and not isinstance(second, (str, bytes))
        and len(first) >= 2
        and len(second) >= 2
    ):
        return None
    x1, y1 = _local_xy(first, origin_x, origin_y)
    x2, y2 = _local_xy(second, origin_x, origin_y)
    thickness = float(wall.get("thickness") or 0.18)
    height = float(wall.get("height") or 3.0)
    if abs(x1 - x2) < abs(y1 - y2):
        size = [thickness / 2.0, abs(y2 - y1) / 2.0, height / 2.0]
    else:
        size = [abs(x2 - x1) / 2.0, thickness / 2.0, height / 2.0]
    return {
        "proxy_id": f"structure_wall_{index:03d}",
        "label": f"structure wall {index}",
        "source": "interiorgs_structure_json",
        "geom_type": "box",
        "pos": [round((x1 + x2) / 2.0, 6), round((y1 + y2) / 2.0, 6), round(height / 2.0, 6)],
        "size": [round(max(0.02, value), 6) for value in size],
        "rgba": [0.50, 0.49, 0.46, 1.0],
        "collision_enabled": True,
        "category": "wall",
    }


def _proxy_by_label(proxies: Sequence[Mapping[str, Any]], *labels: str) -> dict[str, Any] | None:
    wanted = [label.lower() for label in labels]
    candidates = [
        dict(proxy)
        for proxy in proxies
        if any(want in _string(proxy.get("source_label")).lower() for want in wanted)
        and proxy.get("collision_enabled") is True
    ]
    if not candidates:
        return None
    return max(candidates, key=lambda item: float(item.get("volume_m3_estimate") or 0.0))


