def _load_json_mapping(path: str | Path | None) -> dict[str, Any]:
    if not path:
        return {}
    resolved = Path(path).expanduser().resolve()
    if not resolved.is_file():
        return {}
    payload = json.loads(resolved.read_text(encoding="utf-8"))
    return dict(payload) if isinstance(payload, Mapping) else {}


def _load_json_list(path: str | Path | None) -> list[dict[str, Any]]:
    if not path:
        return []
    resolved = Path(path).expanduser().resolve()
    if not resolved.is_file():
        return []
    payload = json.loads(resolved.read_text(encoding="utf-8"))
    if not isinstance(payload, list):
        return []
    return [dict(item) for item in payload if isinstance(item, Mapping)]


def _metadata_origin(occupancy: Mapping[str, Any]) -> tuple[float, float, dict[str, Any]]:
    lower = occupancy.get("lower") or occupancy.get("min") or [0.0, 0.0, 0.0]
    upper = occupancy.get("upper") or occupancy.get("max") or [0.0, 0.0, 0.0]
    if not (
        isinstance(lower, Sequence)
        and not isinstance(lower, (str, bytes))
        and isinstance(upper, Sequence)
        and not isinstance(upper, (str, bytes))
        and len(lower) >= 2
        and len(upper) >= 2
    ):
        return (0.0, 0.0, {"source": "missing_occupancy_bounds"})
    origin_x = (float(lower[0]) + float(upper[0])) / 2.0
    origin_y = (float(lower[1]) + float(upper[1])) / 2.0
    return (
        origin_x,
        origin_y,
        {
            "source": "occupancy_lower_upper_center",
            "lower": [float(lower[0]), float(lower[1])],
            "upper": [float(upper[0]), float(upper[1])],
            "local_bounds": [
                [round(float(lower[0]) - origin_x, 6), round(float(lower[1]) - origin_y, 6)],
                [round(float(upper[0]) - origin_x, 6), round(float(upper[1]) - origin_y, 6)],
            ],
            "scale_m_per_px": occupancy.get("scale"),
        },
    )


def _local_xy(point: Sequence[Any], origin_x: float, origin_y: float) -> list[float]:
    return [float(point[0]) - origin_x, float(point[1]) - origin_y]


def _bbox_bounds(item: Mapping[str, Any]) -> tuple[list[float], list[float]] | None:
    points = item.get("bounding_box")
    if not isinstance(points, Sequence) or isinstance(points, (str, bytes)) or not points:
        return None
    xs: list[float] = []
    ys: list[float] = []
    zs: list[float] = []
    for point in points:
        if not isinstance(point, Mapping):
            continue
        try:
            xs.append(float(point["x"]))
            ys.append(float(point["y"]))
            zs.append(float(point.get("z", 0.0)))
        except (KeyError, TypeError, ValueError):
            continue
    if not xs or not ys:
        return None
    if not zs:  # pragma: no cover - z defaults are appended with every valid xy point.
        zs = [0.0, 0.2]
    return ([min(xs), min(ys), min(zs)], [max(xs), max(ys), max(zs)])


