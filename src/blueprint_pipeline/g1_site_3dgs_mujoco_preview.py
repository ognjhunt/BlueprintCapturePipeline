def run_g1_site_3dgs_mujoco_preview(
    *,
    ply_asset: str | Path,
    spz_asset: str | Path,
    labels_json: str | Path | None = None,
    structure_json: str | Path | None = None,
    occupancy_json: str | Path | None = None,
    occupancy_png: str | Path | None = None,
    job_id: str | None = None,
    job_root: str | Path | None = None,
    g1_model_root: str | Path | None = None,
    allow_fetch_g1_assets: bool = False,
    menagerie_ref: str = DEFAULT_MENAGERIE_REF,
    task_limit: int | None = None,
    spawn_limit: int | None = None,
    camera_ids: Sequence[str] | None = None,
    steps: int = 18,
    fps: int = 8,
    generated_at: str | None = None,
) -> dict[str, Any]:
    if platform.system().lower() == "linux":
        os.environ.setdefault("MUJOCO_GL", "osmesa")
    generated = generated_at or utc_now_iso()
    timestamp = (
        generated.replace("+00:00", "Z")
        .replace(":", "")
        .replace("-", "")
        .replace(".", "")
    )
    resolved_job_id = job_id or f"g1_site_3dgs_mujoco_preview_{timestamp}"
    root = Path(job_root).expanduser().resolve() if job_root else _repo_root() / "robot_eval_jobs"
    job_dir = root / resolved_job_id
    ensure_dir(job_dir)

    camera_id_list = list(camera_ids or DEFAULT_CAMERA_IDS)
    supported_camera_ids = {camera["camera_id"] for camera in _camera_definitions()}
    unknown_cameras = sorted(set(camera_id_list) - supported_camera_ids)
    if unknown_cameras:
        raise ValueError(f"unknown camera ids: {', '.join(unknown_cameras)}")

    mesh_probe = _probe_mujoco_mesh_support(job_dir)
    ply_inspection = inspect_scene_asset(ply_asset)
    spz_inspection = inspect_scene_asset(spz_asset)
    optional_metadata = [
        inspect_optional_scene_metadata(labels_json, metadata_kind="labels_json"),
        inspect_optional_scene_metadata(structure_json, metadata_kind="structure_json"),
        inspect_optional_scene_metadata(occupancy_json, metadata_kind="occupancy_json"),
        inspect_optional_scene_metadata(occupancy_png, metadata_kind="occupancy_png"),
    ]
    scene_visual_source = "spz" if spz_inspection.get("exists") else "gaussian_ply"
    scene_asset_inspection = {
        "schema_version": SCENE_ASSET_INSPECTION_SCHEMA_VERSION,
        "generated_at": generated,
        "status": "completed",
        "assets": [ply_inspection, spz_inspection],
        "optional_scene_metadata": optional_metadata,
        "optional_metadata_can_upgrade_proxy_fidelity": any(
            item.get("status") == "inspected" for item in optional_metadata
        ),
        "mujoco_mesh_support_probe": mesh_probe,
        "scene_visual_source": scene_visual_source,
    }

    g1_root = _resolve_g1_model_root(
        explicit_root=g1_model_root,
        capture_root=job_dir,
        allow_fetch=allow_fetch_g1_assets,
        menagerie_ref=menagerie_ref,
    )
    generated_g1_xml = job_dir / "generated_mjcf" / "menagerie_g1_with_eval_cameras.xml"
    g1_camera_manifest = _write_g1_xml_with_eval_cameras(g1_root / "g1.xml", generated_g1_xml)
    proxies, proxy_source_manifest, scene_anchors = build_scene_proxies_from_metadata(
        labels_json=labels_json,
        structure_json=structure_json,
        occupancy_json=occupancy_json,
    )
    proxy_obj_manifest = _write_proxy_scene_obj(
        job_dir / "generated_mjcf" / "generated_classroom_proxy.obj",
        proxies,
    )
    conversion_attempts = _attempt_visual_asset_mesh_conversion(
        ply_asset=ply_asset,
        spz_asset=spz_asset,
        output_dir=job_dir / "generated_mjcf" / "visual_asset_conversion_attempts",
        ply_inspection=ply_inspection,
        spz_inspection=spz_inspection,
    )
    generated_scene_xml = job_dir / "generated_site_scene.mjcf.xml"
    _write_generated_site_scene_xml(
        output_path=generated_scene_xml,
        g1_xml=generated_g1_xml,
        proxies=proxies,
        proxy_obj=Path(proxy_obj_manifest["path"])
        if proxy_obj_manifest.get("status") == "completed"
        else None,
    )
    # Keep the exact requested alternative filename available for downstream tools.
    shutil.copyfile(generated_scene_xml, job_dir / "generated_site_scene.xml")

    scene_conversion_report = {
        "schema_version": SCENE_CONVERSION_REPORT_SCHEMA_VERSION,
        "generated_at": generated,
        "status": "completed_with_fail_closed_proxy",
        "scene_visual_source": scene_visual_source,
        "visual_sources": ["gaussian_ply", "spz"],
        "mujoco_collision_scene_source": "mjcf_proxy",
        "direct_spz_or_gaussian_ply_mujoco_collision_import_claimed": False,
        "generated_site_scene_xml": str(generated_scene_xml),
        "generated_site_scene_alias_xml": str(job_dir / "generated_site_scene.xml"),
        "proxy_source_manifest": proxy_source_manifest,
        "conversion_blockers": [
            "spz_is_browser_visual_asset_not_mujoco_collision_mesh",
            "gaussian_splat_ply_has_no_supported_mujoco_ply_mesh_decoder",
        ],
        "optional_metadata_inputs": optional_metadata,
        "metadata_conversion_boundary": (
            "labels/structure/occupancy metadata can improve generated collider proxies. "
            "They only upgrade to mesh-derived collision truth if they contain real triangle "
            "geometry, a 3D voxel grid, or enough calibrated occupancy data to reconstruct "
            "colliders without inventing surfaces."
        ),
        "fallback_used": "structured_mjcf_proxy_classroom_scene",
        "conversion_attempts": conversion_attempts,
        "generated_proxy_obj": proxy_obj_manifest,
        "proxy_scene_contents": [
            "floor",
            "walls",
            "chalkboard",
            "teacher desk",
            "student desk cluster",
            "right bookshelf",
            "floor obstruction",
            "lightweight object",
            "drop zone marker",
        ],
        "mujoco_mesh_support_probe": mesh_probe,
    }

    tasks = build_default_tasks(anchors=scene_anchors)
    spawns = build_default_spawns(anchors=scene_anchors)
    if task_limit is not None:
        tasks = tasks[: max(0, task_limit)]
    if spawn_limit is not None:
        spawns = spawns[: max(0, spawn_limit)]
    spawn_manifest = validate_spawns(spawns=spawns, proxies=proxies, generated_at=generated)
    matrix = build_scenario_eval_matrix(
        job_id=resolved_job_id,
        tasks=tasks,
        spawns=spawn_manifest.get("spawns") or [],
        camera_ids=camera_id_list,
        generated_at=generated,
        route_planner_proxies=proxies,
    )
    camera_manifest = {
        "schema_version": CAMERA_MANIFEST_SCHEMA_VERSION,
        "generated_at": generated,
        "status": "completed",
        "requested_camera_ids": camera_id_list,
        "required_camera_ids": list(DEFAULT_CAMERA_IDS),
        "all_required_camera_types_requested": all(camera_id in camera_id_list for camera_id in DEFAULT_CAMERA_IDS),
        "cameras": _camera_definitions(),
        "g1_camera_manifest": g1_camera_manifest,
    }
    episode_manifest = {
        "schema_version": EPISODE_SPEC_SCHEMA_VERSION,
        "generated_at": generated,
        "status": "completed",
        "episode_count": matrix.get("scenario_eval_run_count"),
        "episodes": [
            {
                "episode_id": run.get("episode_id"),
                "scenario_eval_run_id": run.get("scenario_eval_run_id"),
                "task_id": run.get("task_id"),
                "spawn_id": run.get("spawn_id"),
                "camera_ids": run.get("camera_ids"),
                "route_waypoints": run.get("route_waypoints"),
                "expected_thresholds": run.get("expected_thresholds"),
            }
            for run in matrix.get("runs", [])
        ],
    }

    write_json(job_dir / "scene_asset_inspection.json", scene_asset_inspection)
    write_json(job_dir / "scene_conversion_report.json", scene_conversion_report)
    write_json(job_dir / "collider_proxy_plan.json", {
        "schema_version": COLLIDER_PROXY_PLAN_SCHEMA_VERSION,
        "generated_at": generated,
        "status": "completed",
        "mujoco_collision_scene_source": "mjcf_proxy",
        "proxy_source_manifest": proxy_source_manifest,
        "generated_proxy_obj": proxy_obj_manifest,
        "proxy_count": len(proxies),
        "proxies": [dict(proxy) for proxy in proxies],
    })
    write_json(job_dir / "spawn_pose_validation_manifest.json", spawn_manifest)
    write_json(job_dir / "scenario_eval_matrix.json", matrix)
    write_json(job_dir / "camera_manifest.json", camera_manifest)
    write_json(job_dir / "episode_spec_manifest.json", episode_manifest)

    render_result = _render_episodes(
        job_dir=job_dir,
        matrix=matrix,
        tasks=tasks,
        spawn_manifest=spawn_manifest,
        proxies=proxies,
        generated_scene_xml=generated_scene_xml,
        steps=steps,
        fps=fps,
        camera_ids=camera_id_list,
    )
    if render_result.get("status") != "completed":
        blocker = {
            "schema_version": JOB_RUN_MANIFEST_SCHEMA_VERSION,
            "generated_at": generated,
            "job_id": resolved_job_id,
            "status": "blocked",
            "artifact_dir": str(job_dir),
            "blockers": render_result.get("blockers") or ["render_failed"],
            "render_result": dict(render_result),
        }
        write_json(job_dir / "job_run_manifest.json", blocker)
        return {"status": "blocked", "job_dir": str(job_dir), **blocker}

    proof_flags = {
        "scene_visual_source": scene_visual_source,
        "mujoco_collision_scene_source": "mjcf_proxy",
        "unitree_g1_model_source": "google_deepmind_mujoco_menagerie",
        "unitree_g1_model_source_url": G1_SOURCE_URL,
        "unitree_g1_model_path": str(g1_root / "g1.xml"),
        "unitree_g1_asset_spawned": True,
        "controller_grade_execution_proven": False,
        "official_policy_execution_proven": False,
        "wam_vla_runtime_proven": False,
        "wam_evaluator_trace_scored": True,
        "collision_dynamics_validated": False,
        "generated_world_rank_fidelity_result_proven": False,
        "generated_world_policy_evaluation_scope_proven": False,
    }
    artifact_payloads = _write_job_artifacts(
        job_dir=job_dir,
        job_id=resolved_job_id,
        generated_at=generated,
        scene_asset_inspection=scene_asset_inspection,
        scene_conversion_report=scene_conversion_report,
        proxies=proxies,
        generated_proxy_obj=proxy_obj_manifest,
        proxy_source_manifest=proxy_source_manifest,
        spawn_manifest=spawn_manifest,
        matrix=matrix,
        camera_manifest=camera_manifest,
        episode_manifest=episode_manifest,
        render_result=render_result,
        proof_flags=proof_flags,
    )
    write_json(
        job_dir / "unitree_g1_asset_source_manifest.json",
        {
            **_asset_source_manifest(g1_root),
            "generated_eval_camera_xml": str(generated_g1_xml),
        },
    )
    return {
        "status": "completed",
        "job_id": resolved_job_id,
        "job_dir": str(job_dir),
        "generated_site_scene_xml": str(generated_scene_xml),
        "scenario_eval_matrix_path": str(job_dir / "scenario_eval_matrix.json"),
        "video_count": len(render_result.get("video_rows") or []),
        "poster_count": len(render_result.get("poster_rows") or []),
        "summary": artifact_payloads["summary"],
        "proof_flags": proof_flags,
        "artifact_paths": artifact_payloads["job_run_manifest"]["artifact_paths"],
    }


def _parse_camera_ids(value: str | None) -> list[str] | None:
    if not value:
        return None
    return [_safe_id(item) for item in value.split(",") if _string(item)]


