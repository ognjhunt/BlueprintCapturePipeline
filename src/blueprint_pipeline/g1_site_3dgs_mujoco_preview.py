def _add_camera_to_body(root: ET.Element, body_name: str, camera: Mapping[str, str]) -> bool:
    body = root.find(f".//body[@name='{body_name}']")
    if body is None:
        return False
    name = camera["name"]
    for existing in body.findall("camera"):
        if existing.get("name") == name:
            return True
    ET.SubElement(
        body,
        "camera",
        {
            "name": name,
            "pos": camera["pos"],
            "xyaxes": camera["xyaxes"],
            "fovy": camera["fovy"],
        },
    )
    return True


